"""Build the website's owner-supplied photos and mobile crops.

Usage: python scripts/prepare-hotel-photos.py /path/to/HotelPradeep_webp.zip
Requires Pillow locally; not needed for Next.js development or deployment.
"""
import argparse
import json
import re
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("archive", type=Path)
args = parser.parse_args()
plan = json.loads((ROOT / "scripts/hotel-photo-plan.json").read_text())
target = ROOT / "public/images/hotel"
target.mkdir(parents=True, exist_ok=True)


def prepare(item):
    entry, data = item
    filename = re.sub(r"(?<!^)(?=[A-Z])", "-", entry["key"]).lower()
    with Image.open(BytesIO(data)) as original:
        image = ImageOps.exif_transpose(original).convert("RGB")
        desktop = image.copy()
        desktop.thumbnail((1920, 1920), Image.Resampling.LANCZOS)
        desktop_bytes = BytesIO()
        desktop.save(desktop_bytes, "WEBP", quality=87, method=6)
        ratio_w, ratio_h = entry["mobileRatio"]
        crop_width = min(image.width, image.height * ratio_w / ratio_h, 900)
        mobile = ImageOps.fit(
            image,
            (round(crop_width), round(crop_width * ratio_h / ratio_w)),
            method=Image.Resampling.LANCZOS,
            centering=tuple(entry["focus"]),
        )
        mobile_bytes = BytesIO()
        mobile.save(mobile_bytes, "WEBP", quality=84, method=6)
    return entry["key"], filename, desktop_bytes.getvalue(), mobile_bytes.getvalue()


with ZipFile(args.archive) as archive:
    inputs = [(entry, archive.read(entry["source"])) for entry in plan]
with ThreadPoolExecutor(max_workers=4) as pool:
    paths = {}
    for key, filename, desktop_bytes, mobile_bytes in pool.map(prepare, inputs):
        for suffix, data in [("", desktop_bytes), ("-mobile", mobile_bytes)]:
            path = target / f"{filename}{suffix}.webp"
            staging = path.with_suffix(".tmp")
            staging.write_bytes(data)
            staging.replace(path)
            with Image.open(path) as verified:
                verified.load()
        paths[key] = f"/images/hotel/{filename}.webp"
content = "// Generated by scripts/prepare-hotel-photos.py. Edit its photo plan to recrop.\n"
content += "export const hotelPhotos = " + json.dumps(paths, indent=2) + " as const;\n\n"
content += "export const mobilePhotoSources: Record<string, string> = "
content += json.dumps({url: url.replace(".webp", "-mobile.webp") for url in paths.values()}, indent=2) + ";\n"
(ROOT / "src/lib/photo-sources.ts").write_text(content)
print(f"Prepared {len(paths)} desktop photos and {len(paths)} dedicated mobile crops.")
